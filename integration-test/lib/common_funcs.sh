# Re-exec the calling test script inside an unprivileged user + network
# namespace (unshare -nr).  Inside it we are mapped to root with full
# capabilities over any namespace we create, so none of the ip/tc/tuntap
# plumbing below needs sudo.  Call it right after sourcing this file,
# forwarding the script arguments:
#
#   enter_test_namespace "$@"
function enter_test_namespace() {
  if [ -n "${ZPR_TEST_IN_USERNS:-}" ]
  then
    # Already inside; bring up loopback in the orchestration namespace.
    ip link set lo up
    return 0
  fi

  if ! unshare -nr true 2> /dev/null
  then
    echo "ERROR: cannot create an unprivileged user+network namespace (unshare -nr)." >&2
    echo "On Ubuntu 24.04+ this is usually AppArmor's user-namespace restriction;" >&2
    echo "a one-time admin fix is:" >&2
    echo "  echo kernel.apparmor_restrict_unprivileged_userns=0 | sudo tee /etc/sysctl.d/60-zpr-userns.conf" >&2
    echo "  sudo sysctl --system" >&2
    exit 1
  fi

  # zipline divergence from main: ph reads SUDO_UID/SUDO_GID/PKEXEC_UID to
  # decide who owns its control socket and chowns it to that user
  # (admin-api socket_owner.rs, zipline#39).  Inside the user namespace that
  # uid is unmapped, so the chown and the bind would fail.  Drop them so a
  # script started via sudo behaves like one started directly (zipline#191).
  unset SUDO_UID SUDO_GID SUDO_USER SUDO_COMMAND PKEXEC_UID

  export ZPR_TEST_IN_USERNS=1
  # Re-exec through $BASH with an absolute script path: a script started as
  # `bash script.sh` has a bare $0, which unshare would look up on PATH, and
  # need not be executable (review of zl-zpr-core#82).
  exec unshare -nr "$BASH" "$(realpath "$0")" "$@"
}

# Each test network namespace is an anonymous netns pinned by a holder
# process; NETNS_PID maps namespace name -> holder pid.  No /run/netns
# entries and no root privileges are involved, and when the holders die the
# namespaces evaporate, so a crashed test cannot leak namespaces into the
# host.
declare -A NETNS_PID

function new_netns() {
  local NAME=$1

  # --pdeathsig: the holder gets SIGKILL when this shell dies, however it
  # dies.  A SIGKILLed test shell runs no EXIT trap, so destroy_network
  # never sees the holder, and without this it would pin the namespace
  # forever (review of zl-zpr-core#82).  setpriv and unshare both exec, so
  # $! is the holder itself and the shell stays its parent.
  setpriv --pdeathsig KILL unshare -n sleep infinity &
  local PID=$!

  # Wait until the holder has actually unshared its network namespace;
  # entering it before that would target the orchestration namespace.
  local OUR_NS HOLDER_NS
  OUR_NS=$(readlink "/proc/$$/ns/net")
  for ((i = 0; i < 50; ++i))
  do
    HOLDER_NS=$(readlink "/proc/$PID/ns/net" 2> /dev/null || true)
    if [ -n "$HOLDER_NS" ] && [ "$HOLDER_NS" != "$OUR_NS" ]
    then
      NETNS_PID[$NAME]=$PID
      return 0
    fi
    sleep 0.1
  done

  echo "failed to create network namespace $NAME" >&2
  return 1
}

# Run a command in a test namespace created by new_netns.
# NOTE: unlike `ip netns exec`, this only enters the network namespace and
# does not remount /sys, so read interface state via `ip link`, not
# /sys/class/net.
function in_ns() {
  local NAME=$1
  shift

  nsenter -t "${NETNS_PID[$NAME]}" -n -- "$@"
}

# Create a veth pair in the orchestration namespace and move one end into
# each of two test namespaces.  The test namespaces are freshly created, so
# explicit names cannot collide (the old `ip netns` flow had to rely on
# kernel-autogenerated names to dodge a root-namespace name clash).
function connect_ns() {
  local NS_A=$1 IF_A=$2 NS_B=$3 IF_B=$4

  ip link add "$IF_A" type veth peer name "$IF_B"
  ip link set "$IF_A" netns "${NETNS_PID[$NS_A]}"
  ip link set "$IF_B" netns "${NETNS_PID[$NS_B]}"
}

function prefix_log() {
  SYSNAME=$1
  printf -v PREFIX '%10s' "[$SYSNAME]"
  sed "s/^/$PREFIX /"
}

function wait_for() {
  RETRIES=$1
  shift
  CMD=("$@")

  if "${CMD[@]}"
  then return 0
  else RET=$?
  fi

  for ((i = 0; i < RETRIES; ++i))
  do
    sleep 1

    if "${CMD[@]}"
    then return 0
    else RET=$?
    fi
  done

  return "$RET"
}

# Print the PID of the ph process serving control socket $1, or nothing if
# there is none. Expects PH_BIN to be the ph binary path.
#
# The tests launch ph through wrappers (`nsenter ... $PH_BIN ...
# --control-path S`, or `nsenter ... env ... $PH_BIN ...`) whose command
# lines can contain "--control-path S" too, and a signal sent to a wrapper
# is not reliably passed on to ph (zipline#116). So the pattern is anchored
# on $PH_BIN: nsenter and env exec ph, so only ph's own command line starts
# with it.
#
# Both values are escaped, since pgrep reads the pattern as an extended
# regex: otherwise a "+" in the binary path would stop it matching itself,
# and "adapter1.sock" would also match some other process's "adapter1Xsock".
#
# The search is limited to this run's user namespace (pgrep_own): every run
# uses the same relative socket names, so a concurrent run's ph would match
# too (zipline#191).
function ph_pid_for_socket() {
  local bin sock
  bin=$(ere_escape "$PH_BIN")
  sock=$(ere_escape "$1")
  pgrep_own -f "^$bin .*--control-path $sock( |\$)" | head -n 1 || true
}

# pgrep / pkill limited to processes in this script's user namespace.
#
# Each test run is its own `unshare -nr` user namespace, but every run's
# processes share the invoking user's real uid and the host's PID
# namespace, so a bare `pkill -f PATTERN` would also signal a concurrent
# run's matching process (zipline#191).  --ns/--nslist keep it to ours.
function pgrep_own() {
  pgrep --ns $$ --nslist user "$@"
}
function pkill_own() {
  pkill --ns $$ --nslist user "$@"
}

# Print $1 with every extended-regex metacharacter backslash-escaped, so it
# matches only itself when used in a pattern.
function ere_escape() {
  printf '%s' "$1" | sed 's/[][\\.^$*+?(){}|]/\\&/g'
}

# Succeed once process $1 no longer exists. Uses ps rather than `kill -0`,
# which fails with EPERM on a live process we may not signal and would read
# as "exited".
function process_exited() {
  ! ps -p "$1" > /dev/null
}

function destroy_network() {
  # The namespaces are anonymous, pinned only by their holder processes;
  # killing the holders destroys them.
  local NAME
  for NAME in "${!NETNS_PID[@]}"
  do
    kill "${NETNS_PID[$NAME]}" 2> /dev/null || true
  done
  NETNS_PID=()
}

